#!/usr/bin/env python3
"""Embed ordinary .bolt library implementations plus native boundary declarations."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
library = root / "stdlib"
files = sorted(library.rglob("*.bolt"), key=lambda path: path.relative_to(library).parts)
content = "// Generated by tools/embed-stdlib.py from the .bolt sources in stdlib.\n"
for path in files:
    text = path.read_text(encoding="utf-8")
    if ')BOLT_LIB"' in text: raise ValueError("Raw-string delimiter in " + str(path))
    chunks = [text[i:i + 4096] for i in range(0, len(text), 4096)] or [""]
    literals = "\n".join('R"BOLT_LIB(' + chunk + ')BOLT_LIB"' for chunk in chunks)
    content += '{"<bolt-stdlib>/' + path.relative_to(library).as_posix() + '", ' + literals + '},\n'
target = root / "src/stdlib/Embedded.inc"
if not target.exists() or target.read_text(encoding="utf-8") != content:
    target.write_text(content, encoding="utf-8")
